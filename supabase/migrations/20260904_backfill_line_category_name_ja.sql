  ('링코레',          'リングコレクション'),
  ('피타 데포메',     'ぴたでふぉめ'),
  ('츠만데 츠나게떼', 'つまんでつなげて'),
  ('생물대도감',      'いきもの大図鑑'),
  ('오쿠루미',        'おくるみマスコット'),
  ('네무라세타이',    'ねむらせ隊'),
  ('스와라세타이',    'すわらせ隊'),
  ('나라분데스',      'ならぶんです'),
  ('허그콧',          'ハグコット'),
  ('쵸코노코',        'ちょこのっこ'),
  ('코로코레',        'ころコレ')

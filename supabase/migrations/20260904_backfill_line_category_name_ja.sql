-- 2026-09-04에 추가한 24개는 처음부터 name_ja 를 넣었지만, 원래 있던 17개는 전부
-- null 이었다. 지금은 화면이 name_ko 만 쓰지만 line 축을 노출하기로 했으므로
-- 다국어 대응 시 빈칸이 되지 않게 채워둔다.
--
-- 값은 refresh_gacha_product_categories() 의 line_patterns 사전에 있는 일본어
-- 표기에서 가져왔다. 정규식이 여러 표기를 OR 로 묶은 경우 대표 표기 하나만 쓴다.
